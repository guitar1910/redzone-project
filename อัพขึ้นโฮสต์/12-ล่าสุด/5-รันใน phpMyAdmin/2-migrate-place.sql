--  ทำไมต้องมีไฟล์นี้
--    เดิมชื่อจุดถูกอ้างจากตาราง locations เท่านั้น (location_id)
--    ถ้าผู้แจ้งปักหมุดตรงที่ไม่มีในรายการ ระบบจะจับชื่อจุดที่ใกล้ที่สุดมาใส่
--    ซึ่งบางครั้งห่างเป็นกิโลเมตร ทำให้ชื่อจุดไม่ตรงความจริง
--    หลังรันไฟล์นี้ ระบบจะเก็บชื่อที่แสดงจริงไว้ในรายงานแต่ละใบ
--    (เช่น "ใกล้สนามกีฬา ประมาณ 450 ม." หรือชื่อที่ผู้แจ้งพิมพ์เอง)
--
--  ถ้ารันซ้ำจะขึ้น error ว่าคอลัมน์มีอยู่แล้ว — ไม่เป็นไร ข้ามได้เลย
-- ============================================================

SET NAMES utf8mb4;

ALTER TABLE reports
  ADD COLUMN location_name VARCHAR(120) NULL AFTER location_id;

-- เติมชื่อให้รายงานเก่าที่มีอยู่แล้ว จะได้ไม่กลายเป็นค่าว่าง
UPDATE reports r
  LEFT JOIN locations l ON l.location_id = r.location_id
   SET r.location_name = l.name_th
 WHERE r.location_name IS NULL;

-- ตรวจผล: ค่าต้องเป็น 0
-- (รายงานที่ไม่ได้ผูกกับสถานที่ใดตั้งแต่แรก จะว่างอยู่แล้ว ไม่นับว่าผิด
--  หน้าเว็บจะแสดงว่า "ไม่ระบุสถานที่" ให้เอง)
SELECT COUNT(*) AS เติมชื่อไม่สำเร็จ_ต้องเป็น0
  FROM reports
 WHERE location_id IS NOT NULL
   AND (location_name IS NULL OR location_name = '');
